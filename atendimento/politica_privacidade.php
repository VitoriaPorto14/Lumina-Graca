    <h1>Política de Privacidade</h1>
    <p>A <strong>Lumina Graça</strong> tem o compromisso de respeitar a sua privacidade e garantir a segurança dos seus dados pessoais durante toda a sua navegação e compra em nosso site.</p>

    <h2>1. Informações que Coletamos</h2>
    <p>Para processar e entregar seus pedidos, coletamos as seguintes informações fornecidas voluntariamente por você no momento do checkout:</p>
    <ul>
        <li><strong>Dados Pessoais:</strong> Nome completo e e-mail.</li>
        <li><strong>Dados de Entrega:</strong> CEP, logradouro/rua, número, complemento, bairro, cidade e estado.</li>
        <li><strong>Informações de Pedido:</strong> Produto selecionado e forma de pagamento escolhida.</li>
    </ul>

    <h2>2. Como Utilizamos os Seus Dados</h2>
    <p>Os dados coletados são utilizados exclusivamente para as seguintes finalidades:</p>
    <ul>
        <li>Processar e organizar a entrega dos produtos solicitados;</li>
        <li>Fornecer suporte, acompanhamento e atendimento via WhatsApp;</li>
        <li>Confirmar detalhes de pagamento e envio de mercadorias.</li>
    </ul>

    <h2>3. Compartilhamento de Dados</h2>
    <p>A Lumina Graça não vende, aluga ou compartilha seus dados pessoais com terceiros para fins publicitários. Os dados fornecidos são utilizados apenas internamente para a conclusão do seu pedido.</p>

    <h2>4. Comunicação via WhatsApp</h2>
    <p>Ao finalizar um pedido, você tem a opção de direcionar o resumo da compra para o nosso WhatsApp de atendimento. Esse contato é feito diretamente pelo aplicativo e serve apenas para o acompanhamento do seu pedido e esclarecimento de dúvidas.</p>

    <h2>5. Segurança das Informações</h2>
    <p>Adotamos medidas operacionais e técnicas para proteger suas informações pessoais contra acessos não autorizados, perdas ou alterações indevidas.</p>

    <h2>6. Seus Direitos</h2>
    <p>Você tem o direito de solicitar a confirmação, alteração ou exclusão dos seus dados pessoais mantidos em nossos registros a qualquer momento. Para isso, entre em contato conosco através dos nossos canais de atendimento.</p>

    <h2>7. Alterações nesta Política</h2>
    <p>Reservamo-nos o direito de atualizar esta Política de Privacidade periodicamente para refletir melhorias em nossos processos. Recomendamos a consulta regular desta página.</p>

